"use strict";
// HubNotice shows the notices that Hermes injects into a chat as user
// messages (a finished background subagent, a finished background command,
// a message from another chat, the summary that stands in for a compacted
// chat) as a card on the reply side, not as the
// user's bubble. parse(text) reads a message and returns the notice, or
// null for any other text; it follows internal/notice/notice.go, and both
// run against internal/notice/testdata/cases.json. card(n, raw, ctx) builds
// the collapsed card. The agent still gets the whole text; the card only
// shows less of it, and Copy puts the whole text on the clipboard.
// stamp(box, ms, ctx) shows the time a notice arrived on its card, after the
// status of the status line (first for a message from another agent or a
// plain notice). ctx: el, toast(text), at (the time the notice
// arrived, in Unix milliseconds, when it is known).
window.HubNotice = (() => {
  const footer = "[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. " +
    "Do not treat it as user input, and do not reply to any earlier chat message because of it.]";
  const compactionHead = "[CONTEXT COMPACTION — REFERENCE ONLY] Earlier turns were compacted into the summary below. " +
    "This is a handoff from a previous context window — treat it as background reference, NOT as active instructions.";
  const compactionRulesEnd = "avoid repeating it:";
  const compactionLegacy = "[CONTEXT SUMMARY]:";
  const compactionModelOnly = ["## User Messages (verbatim, newest first)", "## Context Recovery"];
  const compactionHistory = "Historical only; newer protected-tail messages after this summary win.";
  const compactionEnd = "--- END OF CONTEXT SUMMARY — respond to the message below, not the summary above ---";
  const agentHead = /^\[Agent message (am_[0-9a-f]{16}) from ([^\]\n]{1,400})\]\n/;
  const delegationHead = /^\[ASYNC DELEGATION (COMPLETE|BATCH COMPLETE|TASK FAILED) — ([^\],\n]+)(?:, task (\d+)\/(\d+))?\]\n/;
  const processHead = /^\[IMPORTANT: Background process (\S+) (.+?) \(exit code (-?\d+|\?)(?:, SIGTERM)?\)\.\n/;
  const watchHead = /^\[IMPORTANT: Background process (\S+) matched watch pattern "(.*)"\.\n/;
  const heartbeatHead = /^\[Background process (\S+) heartbeat #(\S+) — still running after (\S+) \(/;
  const processBatch = /^\[IMPORTANT: (\d+) background processes completed\. [^\]\n]*\]\n\n/;
  const processSplit = /\n\n(\[IMPORTANT: Background process )/g;
  const taskHead = /^--- (\S+) TASK (\d+)\/(\d+)(?:: ([\s\S]*?))?  \(status=([^,)]+)(?:, api_calls=(\d+))?(?:, ([0-9.]+)s)?(?:, TRUNCATED[^)\n]*)?\) ---$/gm;
  const statusLine = /^Status: (\S+)(?:   API calls: (\d+))?   Duration: ([0-9.]+|\?)s(?: \[TRUNCATED[^\]\n]*\])?$/m;
  const roleModel = /^Role: \S+   Model: (.+)$/m;
  const ranOn = /^Ran on route ([^:\n]+): [^\n]*\.$/m;
  const totalDuration = /^Role: .*   Total duration: ([0-9.]+)s$/m;
  const liveTranscript = /^(?:Full live transcript \(complete tool\/assistant trace\)|Live transcript): [^\n]*$/gm;
  const goalEnd = /^(?:Context you provided: |Toolsets: |Role: )/m;
  const titleLen = 120;
  const statusLabels = { failed: "Failed", error: "Failed", rejected: "Failed", cancelled: "Cancelled",
    interrupted: "Interrupted", timeout: "Timed out", stalled: "Stalled", unknown: "Unknown" };

  const cut = (s, n) => {
    const r = Array.from(s);
    return r.length <= n ? s : r.slice(0, n).join("").trim() + "…";
  };
  const short = (s) => cut(s.split(/\s+/).filter(Boolean).join(" "), titleLen);
  const upperFirst = (s) => (s ? s.charAt(0).toUpperCase() + s.slice(1) : s);
  const trimRight = (s) => s.replace(/[ \t\r\n]+$/, "");

  function duration(secs) {
    const f = Number(secs);
    if (!isFinite(f) || f < 0 || secs === "") return "";
    const s = Math.round(f);
    if (s < 60) return s + " sec";
    const total = Math.round(f / 60);
    if (total < 60) return total + " min";
    if (total % 60 === 0) return total / 60 + " h";
    return Math.floor(total / 60) + " h " + (total % 60) + " min";
  }

  function modelName(model) {
    model = model.trim();
    const lower = model.toLowerCase();
    for (const f of ["opus", "sonnet", "haiku"]) if (lower.includes(f)) return upperFirst(f);
    const i = model.lastIndexOf("/");
    return cut(i >= 0 ? model.slice(i + 1) : model, 24);
  }

  function routeName(text, model) {
    const m = ranOn.exec(text);
    return m ? upperFirst(m[1].trim()) : modelName(model);
  }

  function taskRow(goal, status, secs, calls, route, body, truncated) {
    const done = status === "completed" || status === "success";
    let label = "Completed";
    let state = "ok";
    let prefix = "Subagent finished: ";
    if (!done) {
      label = statusLabels[status] || upperFirst(status);
      state = "bad";
      prefix = "Subagent failed: ";
    } else if (truncated) {
      label = "Incomplete";
      state = "bad";
    }
    const t = short(goal);
    const meta = [label];
    const d = duration(secs);
    if (d) meta.push(d);
    if (route) meta.push(route);
    if (calls) meta.push(calls + " calls");
    let result = body.replace(liveTranscript, "");
    const m = ranOn.exec(result);
    if (m) result = result.slice(0, m.index) + result.slice(m.index + m[0].length);
    const row = { title: t ? prefix + t : prefix.trim().replace(/:$/, ""), state, meta };
    if (goal) row.goal = goal;
    if (result.trim()) row.result = result.trim();
    return row;
  }

  const rowNotice = (r) => Object.assign({ kind: "delegation" }, r);

  function field(n, order) {
    const out = {};
    for (const k of order) if (n[k] !== undefined && n[k] !== "" && !(Array.isArray(n[k]) && !n[k].length)) out[k] = n[k];
    return out;
  }

  const ordered = (n) => field(n, ["kind", "title", "state", "meta", "goal", "result", "id", "rows"]);

  function parseSingle(body) {
    const i = body.indexOf("\n--- RESULT ---");
    if (i < 0) return null;
    const head = body.slice(0, i);
    let result = body.slice(i + "\n--- RESULT ---".length);
    const sm = statusLine.exec(head);
    if (!sm) return null;
    let goal = "";
    const gi = ("\n" + head).indexOf("\nOriginal goal: ");
    if (gi >= 0) {
      let g = head.slice(gi + "Original goal: ".length);
      const e = goalEnd.exec(g);
      if (e) g = g.slice(0, e.index);
      goal = g.trim();
    }
    const rm = roleModel.exec(head);
    const route = routeName(head, rm ? rm[1] : "");
    if (result.startsWith("\n")) result = result.slice(1);
    return rowNotice(taskRow(goal, sm[1], sm[3], sm[2] || "", route, result.trim(), sm[0].includes("TRUNCATED")));
  }

  function parseTaskFailed(body) {
    let goal = "";
    const gi = ("\n" + body).indexOf("\nTask: ");
    if (gi >= 0) {
      const g = body.slice(gi + "Task: ".length);
      const e = g.indexOf("\nStatus: ");
      goal = (e >= 0 ? g.slice(0, e) : g).trim();
    }
    const sm = statusLine.exec(body);
    if (!sm) return null;
    let result = "";
    const ei = body.indexOf("\nError: ");
    if (ei >= 0) {
      let e = body.slice(ei + "\nError: ".length);
      for (const sep of ["\nRan on ", "\nLive transcript: "]) {
        const k = e.indexOf(sep);
        if (k >= 0) e = e.slice(0, k);
      }
      result = e.trim();
    }
    return rowNotice(taskRow(goal, sm[1], sm[3], "", routeName(body, ""), result, false));
  }

  function parseBatch(body) {
    const heads = Array.from(body.matchAll(taskHead));
    if (!heads.length) {
      const k = body.indexOf("--- ERROR ---\n");
      if (k < 0) return null;
      return { kind: "delegation", title: "Subagent failed", state: "bad", meta: ["Failed"], result: body.slice(k + "--- ERROR ---\n".length).trim() };
    }
    const head = body.slice(0, heads[0].index);
    const rm = roleModel.exec(head);
    const unitModel = rm ? rm[1] : "";
    const rows = [];
    let bad = 0;
    heads.forEach((m, i) => {
      const end = i + 1 < heads.length ? heads[i + 1].index : body.length;
      const text = body.slice(m.index + m[0].length, end).trim();
      const row = taskRow((m[4] || "").trim(), m[5], m[7] || "", m[6] || "", routeName(text, unitModel), text, m[1] === "⚠");
      if (row.state === "bad") bad++;
      rows.push(row);
    });
    // A unit holds some of a call's tasks; say which.
    const total = Number(heads[0][3]);
    const part = total > rows.length ? partLabel(heads.map((m) => m[2]), String(total)) : "";
    if (rows.length === 1) {
      const one = rowNotice(rows[0]);
      if (part) one.meta = (one.meta || []).concat(part);
      return one;
    }
    const n = { kind: "delegation", rows };
    const ok = rows.length - bad;
    if (bad === 0) {
      n.title = rows.length + " subagents finished";
      n.state = "ok";
    } else if (ok === 0) {
      n.title = rows.length + " subagents failed";
      n.state = "bad";
    } else {
      n.title = rows.length + " subagents finished, " + bad + " failed";
      n.state = "bad";
    }
    n.meta = [];
    if (ok > 0) n.meta.push(ok + " completed");
    if (bad > 0) n.meta.push(bad + " failed");
    const tm = totalDuration.exec(head);
    if (tm) n.meta.push(duration(tm[1]) + " in all");
    if (part) n.meta.push(part);
    return n;
  }

  // partLabel names the tasks of a call that a notice holds: "task 1 of 2"
  // for one, "tasks 1, 3 of 4" for several.
  function partLabel(idx, total) {
    return idx.length === 1 ? "task " + idx[0] + " of " + total : "tasks " + idx.join(", ") + " of " + total;
  }

  function parseDelegation(t) {
    const m = delegationHead.exec(t);
    if (!m) return null;
    const body = t.slice(m[0].length);
    if (m[1] === "COMPLETE") return parseSingle(body);
    if (m[1] === "TASK FAILED") {
      const n = parseTaskFailed(body);
      if (n && m[3]) n.meta = (n.meta || []).concat(partLabel([m[3]], m[4]));
      return n;
    }
    return parseBatch(body);
  }

  function commandAndOutput(t, outHead) {
    const ci = ("\n" + t).indexOf("\nCommand: ");
    if (ci < 0) return null;
    const rest = t.slice(ci + "Command: ".length);
    const sep = "\n" + outHead + "\n";
    const oi = rest.indexOf(sep);
    if (oi < 0) return null;
    let out = rest.slice(oi + sep.length);
    if (out.endsWith("]")) out = out.slice(0, -1);
    return { cmd: rest.slice(0, oi).trim(), out: out.replace(/^\n+|\n+$/g, "") };
  }

  function parseProcess(t) {
    if (t.startsWith("[Background process ")) {
      const m = heartbeatHead.exec(t);
      const co = m && commandAndOutput(t, "Output since last heartbeat:");
      if (!co) return null;
      return { kind: "command", title: "Background command running: " + short(co.cmd), goal: co.cmd, result: co.out,
        meta: ["Still running", "after " + m[3]] };
    }
    const w = watchHead.exec(t);
    if (w) {
      const co = commandAndOutput(t, "Matched output:");
      if (!co) return null;
      return { kind: "command", title: "Background command matched: " + short(co.cmd), goal: co.cmd, result: co.out,
        meta: ["Matched \"" + cut(w[2], 60) + "\""] };
    }
    const m = processHead.exec(t);
    if (!m) return null;
    const co = commandAndOutput(t, "Output:");
    if (!co) return null;
    const n = { kind: "command", title: "Background command finished: " + short(co.cmd), goal: co.cmd, result: co.out };
    const exit = m[3] === "?" ? "Exit unknown" : "Exit " + m[3];
    n.meta = m[2] === "completed normally" || m[2] === "exited" ? [exit] : [upperFirst(m[2]), exit];
    n.state = m[3] === "0" && m[2] === "completed normally" ? "ok" : "bad";
    return n;
  }

  function parseProcessBatch(t) {
    const m = processBatch.exec(t);
    const parts = t.slice(m[0].length).replace(processSplit, "\x00$1").split("\x00");
    const n = { kind: "command", title: m[1] + " background commands finished", state: "ok", rows: [] };
    let bad = 0;
    for (const p of parts) {
      const c = parseProcess(p.trim());
      if (!c) return null;
      if (c.state === "bad") bad++;
      n.rows.push({ title: short(c.goal), state: c.state, meta: c.meta, goal: c.goal, result: c.result });
    }
    if (bad > 0) {
      n.state = "bad";
      n.meta = [bad + " of " + parts.length + " did not exit cleanly"];
    }
    return n;
  }

  function parseAgent(t) {
    const m = agentHead.exec(t);
    let body = t.slice(m[0].length);
    const i = body.indexOf("\n\n");
    if (i >= 0) body = body.slice(i + 2);
    body = body.trim();
    const n = { kind: "agent", title: "Message from " + m[2], id: m[1], result: body };
    for (const l of body.split("\n")) {
      if (l.trim()) {
        n.meta = [cut(l.trim(), 90)];
        break;
      }
    }
    return n;
  }

  function parseGeneric(t) {
    const i = t.indexOf("\n");
    let first = (i >= 0 ? t.slice(0, i) : t).trim();
    const rest = i >= 0 ? t.slice(i + 1) : "";
    if (first.startsWith("[IMPORTANT: ") && first.endsWith("]")) first = first.slice("[IMPORTANT: ".length, -1);
    return { kind: "notice", title: short(first) || "Notice from the agent", result: rest.trim() };
  }

  const trim = (s) => s.replace(/^[ \t\r\n]+|[ \t\r\n]+$/g, "");

  function cutModelOnly(body) {
    let count = 0;
    for (const heading of compactionModelOnly) {
      const start = body.indexOf(heading);
      if (start < 0) continue;
      const end = body.indexOf("\n## ", start + heading.length);
      const section = end >= 0 ? body.slice(start, end) : body.slice(start);
      const m = /The (\d+) compacted message\(s\) remain fully preserved/.exec(section);
      if (m) count = Number(m[1]);
      body = body.slice(0, start) + (end >= 0 ? body.slice(end + 1) : "");
    }
    const kept = body.split("\n").filter((l) => trim(l) !== compactionHistory).join("\n");
    return { body: trim(kept.replace(/\n{3,}/g, "\n\n")), count };
  }

  // compaction is the notice of a summary that stands in for count messages
  // (0 when it is not known).
  function compaction(summary, count) {
    const n = { kind: "compaction", title: "Earlier messages were summarized", result: summary };
    if (count === 1) n.meta = ["1 message before this point"];
    else if (count > 1) n.meta = [count + " messages before this point"];
    return n;
  }

  function parseCompaction(t) {
    let body;
    if (t.startsWith(compactionHead)) {
      const i = t.indexOf(compactionRulesEnd);
      if (i < 0) return null;
      body = t.slice(i + compactionRulesEnd.length);
    } else if (t.startsWith(compactionLegacy)) {
      body = t.slice(compactionLegacy.length);
    } else {
      return null;
    }
    body = trim(body);
    const e = body.lastIndexOf(compactionEnd);
    if (e >= 0 && trim(body.slice(e + compactionEnd.length)) === "") body = trim(body.slice(0, e));
    const cut = cutModelOnly(body);
    return compaction(cut.body, cut.count);
  }

  function parse(text) {
    let t = trimRight(String(text || ""));
    const marked = t.endsWith(footer);
    if (marked) t = trimRight(t.slice(0, -footer.length));
    const summary = parseCompaction(trim(t));
    let n = null;
    if (summary) n = summary;
    else if (agentHead.test(t + "\n")) n = parseAgent(t + "\n");
    else if (t.startsWith("[ASYNC DELEGATION ")) n = parseDelegation(t);
    else if (processBatch.test(t)) n = parseProcessBatch(t);
    else if (t.startsWith("[IMPORTANT: Background process ") || t.startsWith("[Background process ")) n = parseProcess(t);
    if (!n && marked) n = parseGeneric(t);
    if (!n) return null;
    const out = ordered(n);
    if (out.rows) out.rows = out.rows.map((r) => field(r, ["title", "state", "meta", "goal", "result"]));
    return out;
  }

  const previewChars = 480;
  const previewLines = 10;

  // preview is the start of a long text: whole paragraphs or lines up to a
  // limit, with an open code fence closed so the Markdown stays sound.
  function preview(text, lines) {
    const rows = text.split("\n");
    let end = 0;
    let used = 0;
    while (end < rows.length && used + rows[end].length <= previewChars && end < (lines ? previewLines : rows.length)) {
      used += rows[end].length + 1;
      end++;
    }
    if (end >= rows.length) return null;
    let cutAt = rows.slice(0, Math.max(end, 1)).join("\n");
    if (end === 0) cutAt = rows[0].slice(0, previewChars);
    if (!lines && (cutAt.match(/^```/gm) || []).length % 2) cutAt += "\n```";
    return cutAt.trim() + (lines ? "\n…" : "\n\n…");
  }

  const icons = { delegation: "check", command: "terminal", agent: "message", notice: "info", compaction: "archive" };

  function iconName(n) {
    if (n.kind === "delegation") return n.state === "bad" ? "alert" : "checkcircle";
    return icons[n.kind] || "info";
  }

  const durationText = /^\d+ (?:sec|min|h)(?: \d+ min)?$/;

  // metaLine is the status line of a card: the meta, a run length as "ran
  // 38 min", and the time the notice arrived after the status. A message
  // from another agent or a plain notice has no status and shows the time
  // first.
  function metaLine(el, meta, state, kind, at) {
    const line = el("div", "notice-meta" + (kind === "agent" ? " quote" : ""));
    const items = (meta || []).map((m, i) => (i === 0 && state && kind !== "agent" ? el("span", "notice-" + state, m) : kind !== "agent" && durationText.test(m) ? "ran " + m : m));
    if (window.HubTimes.valid(at)) {
      const when = window.HubTimes.stamp(el("span", "notice-when"), at);
      items.splice(kind === "delegation" || kind === "command" ? 1 : 0, 0, when);
    }
    items.forEach((m, i) => {
      if (i) line.append(" · ");
      line.append(m);
    });
    return line;
  }

  function section(ctx, label, text, opts) {
    const { el } = ctx;
    const box = el("div", "notice-sec");
    if (label) box.append(el("b", "", label + ": "));
    const body = el("div", "notice-text" + (opts.pre ? " pre" : " md"));
    box.append(body);
    const part = opts.long ? preview(text, opts.pre) : null;
    const draw = (full) => {
      const shown = full || part === null ? text : part;
      if (opts.pre) {
        body.textContent = "";
        if (window.HubLinkify) window.HubLinkify.append(body, shown);
        else body.textContent = shown;
      }
      else window.hubMarkdown.render(body, shown);
    };
    draw(false);
    if (part !== null) {
      const word = opts.word || (opts.pre ? "Show full output" : "Show full result");
      const more = el("button", "link notice-more", word);
      more.type = "button";
      let full = false;
      more.onclick = () => {
        full = !full;
        draw(full);
        more.textContent = full ? "Show less" : word;
      };
      box.append(more);
    }
    return box;
  }

  function details(ctx, n) {
    const { el } = ctx;
    const body = el("div", "notice-body");
    const pre = n.kind === "command";
    if (n.goal) body.append(section(ctx, pre ? "Command" : "Task", n.goal, { pre, long: false }));
    if (n.result) {
      const label = n.kind === "delegation" ? "Result" : (pre ? "Output" : "");
      body.append(section(ctx, label, n.result, { pre, long: true, word: n.kind === "compaction" ? "Show full summary" : "" }));
    }
    return body;
  }

  function toggle(head, body) {
    head.onclick = () => {
      const open = head.getAttribute("aria-expanded") !== "true";
      head.setAttribute("aria-expanded", open ? "true" : "false");
      body.hidden = !open;
    };
  }

  function chevron() {
    const c = window.HubIcons.icon("chev");
    c.classList.add("notice-chev");
    return c;
  }

  function header(ctx, n, nested, at) {
    const { el } = ctx;
    const head = el("button", "notice-head");
    head.type = "button";
    head.setAttribute("aria-expanded", "false");
    head.append(window.HubIcons.icon(iconName(n)), el("span", "notice-title", n.title), chevron());
    if ((n.meta && n.meta.length) || window.HubTimes.valid(at)) head.append(metaLine(el, n.meta, n.state, n.kind, at));
    if (nested) head.classList.add("nested");
    return head;
  }

  // card builds the collapsed card of notice n; raw is the whole text.
  function card(n, raw, ctx) {
    const { el } = ctx;
    const box = el("div", "notice");
    box.dataset.kind = n.kind;
    if (n.state) box.dataset.state = n.state;
    const head = header(ctx, n, false, ctx.at);
    const body = el("div", "notice-body-wrap");
    body.hidden = true;
    if (n.rows) {
      const list = el("div", "notice-rows");
      for (const r of n.rows) {
        const row = el("div", "notice-row");
        row.dataset.state = r.state || "";
        const rh = header(ctx, { kind: n.kind, title: r.title, state: r.state, meta: r.meta }, true);
        const rb = details(ctx, { kind: n.kind, goal: r.goal, result: r.result });
        rb.hidden = true;
        toggle(rh, rb);
        row.append(rh, rb);
        list.append(row);
      }
      body.append(list);
    }
    body.append(details(ctx, n));
    const copy = window.HubIcons.button("copy", "Copy the whole notice", "ghost ib notice-copy");
    copy.onclick = async () => {
      try {
        await navigator.clipboard.writeText(raw);
        ctx.toast("Copied");
      } catch (_) {
        ctx.toast("The browser did not allow copying");
      }
    };
    body.append(copy);
    toggle(head, body);
    box.append(head, body);
    box.rawText = raw;
    box.notice = n;
    return box;
  }

  function stamp(box, ms, ctx) {
    if (!box.notice || !window.HubTimes.valid(ms)) return;
    const head = box.querySelector(":scope > .notice-head");
    const old = head.querySelector(":scope > .notice-meta");
    const line = metaLine(ctx.el, box.notice.meta, box.notice.state, box.notice.kind, ms);
    if (old) old.replaceWith(line);
    else head.append(line);
  }

  // folded reads a typed message that a compaction handoff came before:
  // the handoff's card and the words after its end line.
  function folded(text) {
    const t = trim(String(text || ""));
    const i = t.lastIndexOf(compactionEnd);
    if (i < 0) return null;
    const tail = trim(t.slice(i + compactionEnd.length));
    const n = tail ? parse(t.slice(0, i)) : null;
    return n && n.kind === "compaction" ? { notice: n, tail } : null;
  }

  return { parse, folded, card, stamp, metaLine };
})();
