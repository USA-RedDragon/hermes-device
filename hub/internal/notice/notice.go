// Package notice reads the notices that Hermes injects into a chat as user
// messages (a finished background subagent, a finished background command,
// a message from another chat, the summary that stands in for a compacted
// chat) so that the page and the Telegram bot can show them as a card or a
// line. It only reads the text for display: the
// agent still gets the text whole. Text that does not match a known header
// reads as nothing, so it stays an ordinary user message.
//
// internal/web/static/notice.js reads the same formats and must give the same
// result; both run against testdata/cases.json.
package notice

import (
	"fmt"
	"math"
	"regexp"
	"strconv"
	"strings"

	"github.com/USA-RedDragon/talaria/hub/internal/hub"
)

// Kinds of notice.
const (
	KindDelegation = "delegation"
	KindCommand    = "command"
	KindAgent      = "agent"
	KindNotice     = "notice"
	KindCompaction = "compaction"
)

// States of a notice: a good outcome, a bad one, or neither.
const (
	StateOK  = "ok"
	StateBad = "bad"
)

const footer = "[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. " +
	"Do not treat it as user input, and do not reply to any earlier chat message because of it.]"

const titleLen = 120

// Row is one task of a batch, or one command of a batch of commands.
type Row struct {
	Title  string   `json:"title"`
	State  string   `json:"state,omitempty"`
	Meta   []string `json:"meta,omitempty"`
	Goal   string   `json:"goal,omitempty"`
	Result string   `json:"result,omitempty"`
}

// Notice is what a notice text says, for display.
type Notice struct {
	Kind   string   `json:"kind"`
	Title  string   `json:"title"`
	State  string   `json:"state,omitempty"`
	Meta   []string `json:"meta,omitempty"`
	Goal   string   `json:"goal,omitempty"`
	Result string   `json:"result,omitempty"`
	ID     string   `json:"id,omitempty"`
	Rows   []Row    `json:"rows,omitempty"`
}

// Line is the notice as one line of text.
func (n *Notice) Line() string {
	meta := n.Meta
	if len(meta) > 2 {
		meta = meta[:2]
	}
	if n.Kind == KindAgent || n.Kind == KindCompaction || len(meta) == 0 {
		return n.Title
	}
	return n.Title + " (" + strings.Join(meta, ", ") + ")"
}

var (
	delegationHead = regexp.MustCompile(`^\[ASYNC DELEGATION (COMPLETE|BATCH COMPLETE|TASK FAILED) — ([^\],\n]+)(?:, task (\d+)/(\d+))?\]\n`)
	processHead    = regexp.MustCompile(`^\[IMPORTANT: Background process (\S+) (.+?) \(exit code (-?\d+|\?)(?:, SIGTERM)?\)\.\n`)
	watchHead      = regexp.MustCompile(`^\[IMPORTANT: Background process (\S+) matched watch pattern "(.*)"\.\n`)
	heartbeatHead  = regexp.MustCompile(`^\[Background process (\S+) heartbeat #(\S+) — still running after (\S+) \(`)
	processBatch   = regexp.MustCompile(`^\[IMPORTANT: (\d+) background processes completed\. [^\]\n]*\]\n\n`)
	processSplit   = regexp.MustCompile(`\n\n(\[IMPORTANT: Background process )`)
	taskHead       = regexp.MustCompile(`(?m)^--- (\S+) TASK (\d+)/(\d+)(?:: ((?s:.*?)))?  \(status=([^,)]+)(?:, api_calls=(\d+))?(?:, ([0-9.]+)s)?(?:, TRUNCATED[^)\n]*)?\) ---$`)
	statusLine     = regexp.MustCompile(`(?m)^Status: (\S+)(?:   API calls: (\d+))?   Duration: ([0-9.]+|\?)s(?: \[TRUNCATED[^\]\n]*\])?$`)
	roleModel      = regexp.MustCompile(`(?m)^Role: \S+   Model: (.+)$`)
	ranOn          = regexp.MustCompile(`(?m)^Ran on route ([^:\n]+): [^\n]*\.$`)
	totalDuration  = regexp.MustCompile(`(?m)^Role: .*   Total duration: ([0-9.]+)s$`)
	liveTranscript = regexp.MustCompile(`(?m)^(?:Full live transcript \(complete tool/assistant trace\)|Live transcript): [^\n]*$`)
	goalEnd        = regexp.MustCompile(`(?m)^(?:Context you provided: |Toolsets: |Role: )`)
)

// Parse reads a user message as a notice, or returns nil when it is none.
func Parse(text string) *Notice {
	t := strings.TrimRight(text, " \t\r\n")
	marked := strings.HasSuffix(t, footer)
	if marked {
		t = strings.TrimRight(strings.TrimSuffix(t, footer), " \t\r\n")
	}
	var n *Notice
	summary, count, compacted := hub.CompactionSummary(t)
	switch {
	case compacted:
		n = Compaction(summary, count)
	case hub.AgentHeaderRE.MatchString(t + "\n"):
		n = parseAgent(t + "\n")
	case strings.HasPrefix(t, "[ASYNC DELEGATION "):
		n = parseDelegation(t)
	case processBatch.MatchString(t):
		n = parseProcessBatch(t)
	case strings.HasPrefix(t, "[IMPORTANT: Background process "), strings.HasPrefix(t, "[Background process "):
		n = parseProcess(t)
	}
	if n == nil && marked {
		n = parseGeneric(t)
	}
	return n
}

// Compaction is the notice of a summary that stands in for count messages
// (0 when it is not known).
func Compaction(summary string, count int) *Notice {
	n := &Notice{Kind: KindCompaction, Title: "Earlier messages were summarized", Result: summary}
	switch {
	case count == 1:
		n.Meta = []string{"1 message before this point"}
	case count > 1:
		n.Meta = []string{fmt.Sprintf("%d messages before this point", count)}
	}
	return n
}

func parseAgent(t string) *Notice {
	m := hub.AgentHeaderRE.FindStringSubmatch(t)
	body := t[len(m[0]):]
	if _, rest, ok := strings.Cut(body, "\n\n"); ok {
		body = rest
	}
	body = strings.TrimSpace(body)
	n := &Notice{Kind: KindAgent, Title: "Message from " + m[2], ID: m[1], Result: body}
	for _, l := range strings.Split(body, "\n") {
		if l = strings.TrimSpace(l); l != "" {
			n.Meta = []string{cut(l, 90)}
			break
		}
	}
	return n
}

func parseGeneric(t string) *Notice {
	first, rest, _ := strings.Cut(t, "\n")
	first = strings.TrimSpace(first)
	if strings.HasPrefix(first, "[IMPORTANT: ") && strings.HasSuffix(first, "]") {
		first = strings.TrimSuffix(strings.TrimPrefix(first, "[IMPORTANT: "), "]")
	}
	n := &Notice{Kind: KindNotice, Title: short(first), Result: strings.TrimSpace(rest)}
	if n.Title == "" {
		n.Title = "Notice from Hermes"
	}
	return n
}

func parseDelegation(t string) *Notice {
	m := delegationHead.FindStringSubmatch(t)
	if m == nil {
		return nil
	}
	body := t[len(m[0]):]
	switch m[1] {
	case "COMPLETE":
		return parseSingle(body)
	case "TASK FAILED":
		n := parseTaskFailed(body)
		if n != nil && m[3] != "" {
			n.Meta = append(n.Meta, partLabel([]string{m[3]}, m[4]))
		}
		return n
	}
	return parseBatch(body)
}

func parseSingle(body string) *Notice {
	head, result, ok := strings.Cut(body, "\n--- RESULT ---")
	if !ok {
		return nil
	}
	sm := statusLine.FindStringSubmatch(head)
	if sm == nil {
		return nil
	}
	goal := ""
	if i := strings.Index("\n"+head, "\nOriginal goal: "); i >= 0 {
		g := head[i+len("Original goal: "):]
		if e := goalEnd.FindStringIndex(g); e != nil {
			g = g[:e[0]]
		}
		goal = strings.TrimSpace(g)
	}
	route := routeName(head, roleModelOf(head))
	result = strings.TrimSpace(strings.TrimPrefix(result, "\n"))
	row := taskRow(goal, sm[1], sm[3], sm[2], route, result, strings.Contains(sm[0], "TRUNCATED"))
	return rowNotice(row)
}

func parseTaskFailed(body string) *Notice {
	goal := ""
	if i := strings.Index("\n"+body, "\nTask: "); i >= 0 {
		g, _, _ := strings.Cut(body[i+len("Task: "):], "\nStatus: ")
		goal = strings.TrimSpace(g)
	}
	sm := statusLine.FindStringSubmatch(body)
	if sm == nil {
		return nil
	}
	result := ""
	if _, e, ok := strings.Cut(body, "\nError: "); ok {
		e, _, _ = strings.Cut(e, "\nRan on ")
		e, _, _ = strings.Cut(e, "\nLive transcript: ")
		result = strings.TrimSpace(e)
	}
	row := taskRow(goal, sm[1], sm[3], "", routeName(body, ""), result, false)
	return rowNotice(row)
}

func roleModelOf(head string) string {
	if m := roleModel.FindStringSubmatch(head); m != nil {
		return m[1]
	}
	return ""
}

func parseBatch(body string) *Notice {
	idx := taskHead.FindAllStringSubmatchIndex(body, -1)
	if len(idx) == 0 {
		if _, e, ok := strings.Cut(body, "--- ERROR ---\n"); ok {
			return &Notice{Kind: KindDelegation, Title: "Subagent failed", State: StateBad, Meta: []string{labelFailed}, Result: strings.TrimSpace(e)}
		}
		return nil
	}
	head := body[:idx[0][0]]
	unitModel := roleModelOf(head)
	rows := make([]Row, 0, len(idx))
	bad := 0
	var seen []string
	for i, loc := range idx {
		end := len(body)
		if i+1 < len(idx) {
			end = idx[i+1][0]
		}
		g := func(k int) string {
			if loc[2*k] < 0 {
				return ""
			}
			return body[loc[2*k]:loc[2*k+1]]
		}
		text := strings.TrimSpace(body[loc[1]:end])
		row := taskRow(strings.TrimSpace(g(4)), g(5), g(7), g(6), routeName(text, unitModel), text, g(1) == "⚠")
		if row.State == StateBad {
			bad++
		}
		rows = append(rows, row)
		seen = append(seen, g(2))
	}
	// A unit holds some of a call's tasks; say which, so "1 subagent" of a
	// 2-task call does not read as the whole call.
	part := ""
	if total, _ := strconv.Atoi(body[idx[0][6]:idx[0][7]]); total > len(rows) {
		part = partLabel(seen, strconv.Itoa(total))
	}
	if len(rows) == 1 {
		n := rowNotice(rows[0])
		if part != "" {
			n.Meta = append(n.Meta, part)
		}
		return n
	}
	n := &Notice{Kind: KindDelegation, Rows: rows}
	ok := len(rows) - bad
	switch {
	case bad == 0:
		n.Title = fmt.Sprintf("%d subagents finished", len(rows))
		n.State = StateOK
	case ok == 0:
		n.Title = fmt.Sprintf("%d subagents failed", len(rows))
		n.State = StateBad
	default:
		n.Title = fmt.Sprintf("%d subagents finished, %d failed", len(rows), bad)
		n.State = StateBad
	}
	if ok > 0 {
		n.Meta = append(n.Meta, fmt.Sprintf("%d completed", ok))
	}
	if bad > 0 {
		n.Meta = append(n.Meta, fmt.Sprintf("%d failed", bad))
	}
	if m := totalDuration.FindStringSubmatch(head); m != nil {
		n.Meta = append(n.Meta, duration(m[1])+" in all")
	}
	if part != "" {
		n.Meta = append(n.Meta, part)
	}
	return n
}

// partLabel names the tasks of a call that a notice holds: "task 1 of 2" for
// one, "tasks 1, 3 of 4" for several.
func partLabel(idx []string, total string) string {
	if len(idx) == 1 {
		return "task " + idx[0] + " of " + total
	}
	return "tasks " + strings.Join(idx, ", ") + " of " + total
}

func rowNotice(r Row) *Notice {
	n := &Notice{Kind: KindDelegation, Title: r.Title, State: r.State, Meta: r.Meta, Goal: r.Goal, Result: r.Result}
	return n
}

const labelFailed = "Failed"

func statusLabel(status string) string {
	switch status {
	case "failed", "error", "rejected":
		return labelFailed
	case "cancelled", "interrupted", "stalled", "unknown":
		return upperFirst(status)
	case "timeout":
		return "Timed out"
	}
	return upperFirst(status)
}

func taskRow(goal, status, secs, calls, route, body string, truncated bool) Row {
	done := status == "completed" || status == "success"
	label, state, prefix := "Completed", StateOK, "Subagent finished: "
	switch {
	case !done:
		label, state, prefix = statusLabel(status), StateBad, "Subagent failed: "
	case truncated:
		label, state = "Incomplete", StateBad
	}
	title := strings.TrimSuffix(prefix, " ")
	if t := short(goal); t != "" {
		title = prefix + t
	}
	meta := []string{label}
	if secs != "" {
		if d := duration(secs); d != "" {
			meta = append(meta, d)
		}
	}
	if route != "" {
		meta = append(meta, route)
	}
	if calls != "" {
		meta = append(meta, calls+" calls")
	}
	result := liveTranscript.ReplaceAllString(body, "")
	if m := ranOn.FindStringIndex(result); m != nil {
		result = result[:m[0]] + result[m[1]:]
	}
	return Row{Title: title, State: state, Meta: meta, Goal: goal, Result: strings.TrimSpace(result)}
}

func routeName(text, model string) string {
	if m := ranOn.FindStringSubmatch(text); m != nil {
		return upperFirst(strings.TrimSpace(m[1]))
	}
	return modelName(model)
}

func modelName(model string) string {
	model = strings.TrimSpace(model)
	lower := strings.ToLower(model)
	for _, f := range []string{"opus", "sonnet", "haiku"} {
		if strings.Contains(lower, f) {
			return upperFirst(f)
		}
	}
	if i := strings.LastIndex(model, "/"); i >= 0 {
		model = model[i+1:]
	}
	return cut(model, 24)
}

func parseProcess(t string) *Notice {
	switch {
	case strings.HasPrefix(t, "[Background process "):
		m := heartbeatHead.FindStringSubmatch(t)
		if m == nil {
			return nil
		}
		cmd, out, ok := commandAndOutput(t, "Output since last heartbeat:")
		if !ok {
			return nil
		}
		return &Notice{Kind: KindCommand, Title: "Background command running: " + short(cmd), Goal: cmd, Result: out,
			Meta: []string{"Still running", "after " + m[3]}}
	case watchHead.MatchString(t):
		m := watchHead.FindStringSubmatch(t)
		cmd, out, ok := commandAndOutput(t, "Matched output:")
		if !ok {
			return nil
		}
		return &Notice{Kind: KindCommand, Title: "Background command matched: " + short(cmd), Goal: cmd, Result: out,
			Meta: []string{"Matched \"" + cut(m[2], 60) + "\""}}
	}
	m := processHead.FindStringSubmatch(t)
	if m == nil {
		return nil
	}
	cmd, out, ok := commandAndOutput(t, "Output:")
	if !ok {
		return nil
	}
	n := &Notice{Kind: KindCommand, Title: "Background command finished: " + short(cmd), Goal: cmd, Result: out}
	exit := "Exit " + m[3]
	if m[3] == "?" {
		exit = "Exit unknown"
	}
	if m[2] == "completed normally" || m[2] == "exited" {
		n.Meta = []string{exit}
	} else {
		n.Meta = []string{upperFirst(m[2]), exit}
	}
	n.State = StateBad
	if m[3] == "0" && m[2] == "completed normally" {
		n.State = StateOK
	}
	return n
}

func commandAndOutput(t, outHead string) (cmd, out string, ok bool) {
	_, rest, found := strings.Cut("\n"+t, "\nCommand: ")
	if !found {
		return "", "", false
	}
	cmd, out, found = strings.Cut(rest, "\n"+outHead+"\n")
	if !found {
		return "", "", false
	}
	out = strings.TrimSuffix(out, "]")
	return strings.TrimSpace(cmd), strings.Trim(out, "\n"), true
}

func parseProcessBatch(t string) *Notice {
	m := processBatch.FindStringSubmatch(t)
	rest := t[len(m[0]):]
	parts := strings.Split(processSplit.ReplaceAllString(rest, "\x00$1"), "\x00")
	n := &Notice{Kind: KindCommand, Title: m[1] + " background commands finished", State: StateOK}
	bad := 0
	for _, p := range parts {
		c := parseProcess(strings.TrimSpace(p))
		if c == nil {
			return nil
		}
		if c.State == StateBad {
			bad++
		}
		n.Rows = append(n.Rows, Row{Title: short(c.Goal), State: c.State, Meta: c.Meta, Goal: c.Goal, Result: c.Result})
	}
	if bad > 0 {
		n.State = StateBad
		n.Meta = []string{fmt.Sprintf("%d of %d did not exit cleanly", bad, len(parts))}
	}
	return n
}

func short(s string) string {
	return cut(strings.Join(strings.Fields(s), " "), titleLen)
}

func cut(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	return strings.TrimSpace(string(r[:n])) + "…"
}

func upperFirst(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	return strings.ToUpper(string(r[:1])) + string(r[1:])
}

func duration(secs string) string {
	f, err := strconv.ParseFloat(secs, 64)
	if err != nil || f < 0 {
		return ""
	}
	s := int(math.Round(f))
	if s < 60 {
		return fmt.Sprintf("%d sec", s)
	}
	total := int(math.Round(f / 60))
	if total < 60 {
		return fmt.Sprintf("%d min", total)
	}
	if total%60 == 0 {
		return fmt.Sprintf("%d h", total/60)
	}
	return fmt.Sprintf("%d h %d min", total/60, total%60)
}
