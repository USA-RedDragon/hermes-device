// The exact formats of text that Hermes, Claude Code and the importer put
// into user messages, for rows that carry none of the marks Classify reads
// first. Each is matched by its opening text as its writer spells it, so a
// message the user typed is read as typed.

type prefixCard struct {
	prefix, title string
}

// wholeCards are rows that are a card in full, by their opening text.
func wholeCards() []prefixCard {
	return []prefixCard{
		// tui_gateway/session_auto_continue.py _auto_continue_note.
		{"[System note: Your previous turn was interrupted mid-run", titleResumed},
		// gateway/run.py build_resume_recovery_note (an auto-resume turn stores it).
		{"[System note: The previous turn was interrupted by ", "Picked up after a restart"},
		// cron/scheduler_prompt.py _CRON_HINT and the skill lines before it.
		{"[IMPORTANT: You are running as a scheduled cron job.", titleCronInput},
		{"[IMPORTANT: The user has invoked the \"", titleCronInput},
		{"[IMPORTANT: The following skill(s) were listed for this job but could not be found", titleCronInput},
		// Claude Code's compaction summary (both variants of its bundle's
		// text start so), as hermes sessions import keeps it.
		{"This session is being continued from a previous conversation that ran out of context.", "Earlier conversation summarized"},
		// hermes_cli/foreign_sessions.py _merge_turns.
		{"(imported conversation begins with an assistant reply)", "Imported conversation"},
	}
}

var (
	// gateway/slash_commands_model.py and hermes_cli/cli_model_switch_mixin.py.
	modelNote      = regexp.MustCompile(`^\[Note: model was just switched from [^\n]*\]`)
	modelResetNote = regexp.MustCompile(`^\[Note: the session model override was cleared; [^\n]*\]`)
	// gateway/slash_commands.py _handle_reload_skills_command.
	skillsNote = regexp.MustCompile(`^\[USER INITIATED SKILLS RELOAD:\n[\s\S]*?\nUse skills_list to see the updated catalog\.\]`)
	// gateway/run_turn_runner.py _prepare_turn_message (model only).
	recoveryNote = regexp.MustCompile(`^\[System note: A new message has arrived\. The conversation history contains pending tool outputs from an interrupted turn\.[^\n]*\]`)
)

type leadNote struct {
	re    *regexp.Regexp
	title string
}

// leadNotes are notes Hermes put before the user's text; the text after the
// blank line that ends one is what the user typed. A note with no title is
// dropped without a card.
func leadNotes() []leadNote {
	return []leadNote{{modelNote, titleModel}, {modelResetNote, titleModel}, {skillsNote, "Skills reloaded"}, {recoveryNote, ""}}
}

// Claude Code's own tags (its bundle's tag list): blocks it adds to user
// turns. hermes sessions import drops a turn that starts with some of them
// and keeps the rest, merged with the next turn.
var (
	ccBlock       = regexp.MustCompile(`(?m)^<(system-reminder|task-notification|local-command-stdout|local-command-stderr|local-command-caveat|bash-stdout|bash-stderr|bash-exit-code|user-prompt-submit-hook)>[\s\S]*?</(?:system-reminder|task-notification|local-command-stdout|local-command-stderr|local-command-caveat|bash-stdout|bash-stderr|bash-exit-code|user-prompt-submit-hook)>[ \t]*\n?`)
	ccCommand     = regexp.MustCompile(`(?m)^(?:<command-message>[^\n]*</command-message>\n?)?<command-name>(/?[^<\n]*)</command-name>(?:\n?<command-message>[^\n]*</command-message>)?(?:\n?<command-args>([\s\S]*?)</command-args>)?`)
	ccBash        = regexp.MustCompile(`(?m)^<bash-input>([\s\S]*?)</bash-input>`)
	ccInterrupted = regexp.MustCompile(`(?m)^\[Request interrupted by user[^\]\n]*\][ \t]*\n?`)
	ccCaveat      = regexp.MustCompile(`(?m)^Caveat: The messages below were generated by the user while running local commands\.[^\n]*\n?`)
	ccTaskSummary = regexp.MustCompile(`<summary>([^<\n]*)</summary>`)
)

// ccQuiet reports whether a tag's blocks are model plumbing, dropped without
// a card.
func ccQuiet(tag string) bool {
	return tag == "system-reminder" || tag == "local-command-caveat" || tag == "user-prompt-submit-hook"
}

func fallback(r Row) View {
	t := strings.TrimSpace(r.Text)
	// Hermes hides these in its history (tui_gateway/session_history.py
	// _is_display_hidden_marker); its other reads keep them.
	if strings.HasPrefix(t, "[System:") {
		return View{Show: ShowHidden, Why: whyText}
	}
	for _, w := range wholeCards() {
		if strings.HasPrefix(t, w.prefix) {
			return View{Show: ShowCard, Notice: &notice.Notice{Kind: notice.KindNotice, Title: w.title, Result: t}, Why: whyText}
		}
	}
	var cards []string
	title := ""
	for changed := true; changed; {
		changed = false
		for _, n := range leadNotes() {
			loc := n.re.FindStringIndex(t)
			if loc == nil {
				continue
			}
			if n.title != "" {
				cards = append(cards, t[:loc[1]])
				if title == "" {
					title = n.title
				}
			}
			t = strings.TrimLeft(t[loc[1]:], " \t\r\n")
			changed = true
		}
	}
	t, ccCards, ccTitle, cut := cutClaudeCode(t)
	cards = append(cards, ccCards...)
	if title == "" {
		title = ccTitle
	}
	if len(cards) == 0 && !cut && t == strings.TrimSpace(r.Text) {
		return View{Show: ShowUser, Text: r.Text, Why: whyTyped}
	}
	var n *notice.Notice
	if len(cards) > 0 {
		n = &notice.Notice{Kind: notice.KindNotice, Title: title, Result: strings.Join(cards, "\n\n")}
	}
	if t == "" {
		if n == nil {
			return View{Show: ShowHidden, Why: whyText}
		}
		return View{Show: ShowCard, Notice: n, Why: whyText}
	}
	return View{Show: ShowUser, Text: t, Notice: n, Why: whyText}
}

// cutClaudeCode takes Claude Code's blocks out of an imported message: the
// command and shell lines the user typed stay as "/name args" and "! cmd",
// outputs and notifications go to a card, reminders are dropped.
func cutClaudeCode(t string) (string, []string, string, bool) {
	if !strings.Contains(t, "<") && !strings.Contains(t, "[Request interrupted by user") && !strings.Contains(t, "Caveat: ") {
		return t, nil, "", false
	}
	before := t
	var cards []string
	title := ""
	add := func(s, tt string) {
		if s = strings.TrimSpace(s); s != "" {
			cards = append(cards, s)
			if title == "" {
				title = tt
			}
		}
	}
	t = ccBlock.ReplaceAllStringFunc(t, func(b string) string {
		tag := b[1:strings.IndexByte(b, '>')]
		switch {
		case ccQuiet(tag):
		case tag == "task-notification":
			tt := "Background task notice"
			if m := ccTaskSummary.FindStringSubmatch(b); m != nil {
				tt = firstLine(m[1])
			}
			add(b, tt)
		default:
			add(b, "Command output")
		}
		return ""
	})
	t = ccCommand.ReplaceAllStringFunc(t, func(b string) string {
		m := ccCommand.FindStringSubmatch(b)
		name := strings.TrimSpace(m[1])
		if name != "" && !strings.HasPrefix(name, "/") {
			name = "/" + name
		}
		if args := strings.TrimSpace(m[2]); args != "" {
			return name + " " + args
		}
		return name
	})
	t = ccBash.ReplaceAllString(t, "! $1")
	t = ccInterrupted.ReplaceAllStringFunc(t, func(b string) string {
		add(b, "Interrupted")
		return ""
	})
	t = ccCaveat.ReplaceAllString(t, "")
	if t == before {
		return t, nil, "", false
	}
	return strings.TrimSpace(collapseBlank(t)), cards, title, true
}

var blankRuns = regexp.MustCompile(`\n{3,}`)

func collapseBlank(s string) string {
	return blankRuns.ReplaceAllString(s, "\n\n")
}
